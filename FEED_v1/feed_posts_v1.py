def bold(text):
    """MMK 코멘트처럼 영문 제목을 굵은 유니코드 글자로 바꾼다."""
    out = []
    for ch in text:
        if 'A' <= ch <= 'Z':
            out.append(chr(0x1D5D4 + ord(ch) - ord('A')))
        elif 'a' <= ch <= 'z':
            out.append(chr(0x1D5EE + ord(ch) - ord('a')))
        else:
            out.append(ch)
    return ''.join(out)


def mmk(en, kr, line):
    return [bold(en), ': ' + kr, line]


